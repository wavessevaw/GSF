#!/usr/bin/env python3
"""Write a C header with SPIR-V words: embed_spirv.py out.h name=file.spv ..."""
import struct
import sys


def main():
    out, items = sys.argv[1], sys.argv[2:]
    lines = ["/* generated by tools/embed_spirv.py from the shaders directory; do not edit */",
             "#ifndef TE_SHADERS_H", "#define TE_SHADERS_H", "#include <stdint.h>"]
    for item in items:
        name, path = item.split("=", 1)
        data = open(path, "rb").read()
        if len(data) % 4 or struct.unpack_from("<I", data)[0] != 0x07230203:
            raise SystemExit(f"{path} is not SPIR-V")
        words = struct.unpack(f"<{len(data) // 4}I", data)
        body = ",".join(f"0x{w:08x}" for w in words)
        lines.append(f"static const uint32_t te_spv_{name}[{len(words)}] = {{{body}}};")
    lines.append("#endif")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
