"""Builds py_modules/kedavra_hud_font.py: an Inter glyph atlas for the on-screen HUD.

The Deck's plugin Python has no imaging library, so glyphs are rasterised here once (Pillow,
Inter from the system fonts, SIL Open Font License 1.1) and stored as 8-bit coverage.
  python3 tools/make_hud_font.py [FONT_DIR]
"""
import base64
import json
import sys
import zlib
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CHARS = " %+-./0123456789:ABCDEFGHIJKLMNOPQRSTUVWXYZx—"
SCALES = (1.0, 1.5, 2.0, 3.0)  # 3.0: a 4K TV
# style: (font file, pixel size at scale 1, letter spacing)
STYLES = {
    "fps": ("Inter-Bold.otf", 17, 0.0),
    "val": ("Inter-SemiBold.otf", 13, 0.0),
    "sub": ("Inter-SemiBold.otf", 8, 0.2),
    "lab": ("Inter-SemiBold.otf", 8, 0.6),
}


def build(font_dir: Path) -> dict:
    atlas = {}
    for style, (name, px, spacing) in STYLES.items():
        for s in SCALES:
            font = ImageFont.truetype(str(font_dir / name), round(px * s))
            ascent, descent = font.getmetrics()
            glyphs = {}
            for ch in CHARS:
                x0, y0, x1, y1 = font.getbbox(ch)
                w, h = max(0, x1 - x0), max(0, y1 - y0)
                img = Image.new("L", (max(1, w), max(1, h)), 0)
                ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255)
                glyphs[ch] = {"x0": x0, "y0": y0, "w": w, "h": h, "adv": font.getlength(ch),
                              "a": base64.b64encode(img.tobytes() if w and h else b"").decode()}
            atlas[f"{style}@{s}"] = {"ascent": ascent, "descent": descent,
                                     "spacing": spacing * s, "glyphs": glyphs}
    return atlas


def main() -> None:
    font_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter")
    blob = base64.b64encode(zlib.compress(json.dumps(build(font_dir), separators=(",", ":")).encode(), 9)).decode()
    lines = [blob[i:i + 100] for i in range(0, len(blob), 100)]
    out = Path(__file__).resolve().parent.parent / "py_modules" / "kedavra_hud_font.py"
    out.write_text('"""Inter glyph atlas (SIL Open Font License 1.1) for the HUD. Generated by\n'
                   'tools/make_hud_font.py; do not edit."""\nDATA = (\n'
                   + "".join(f'    "{l}"\n' for l in lines) + ")\n")
    print(f"{out}: {len(blob)} bytes")


if __name__ == "__main__":
    main()
