"""Builds the plugin's logo assets from docs/img/logo.png:
  py_modules/kedavra_hud_logo.py  RGBA bitmaps for the on-screen HUD (one per HUD scale)
  src/logo.ts                     a small PNG data URI for the Decky panel header
  python3 tools/make_logo_assets.py [LOGO_PNG]
"""
import base64
import io
import sys
import zlib
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
HUD_SIZES = {"1.0": 22, "1.5": 33, "2.0": 44, "3.0": 66}
PANEL_PX = 96


def main() -> None:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parents[1] / "docs/img/logo.png"
    logo = Image.open(src).convert("RGBA")
    bitmaps = {}
    for scale, px in HUD_SIZES.items():
        im = logo.resize((px, px), Image.LANCZOS)
        bitmaps[scale] = (px, base64.b64encode(zlib.compress(im.tobytes(), 9)).decode())
    lines = ["# SPDX-License-Identifier: GPL-3.0-or-later",
             "# Generated by tools/make_logo_assets.py from docs/img/logo.png. Do not edit.",
             "# HUD scale -> (size in pixels, base64 of zlib-compressed RGBA rows).",
             "LOGO = {"]
    lines += [f'    "{s}": ({px}, "{data}"),' for s, (px, data) in bitmaps.items()]
    lines.append("}")
    (ROOT / "py_modules/kedavra_hud_logo.py").write_text("\n".join(lines) + "\n")

    buf = io.BytesIO()
    logo.resize((PANEL_PX, PANEL_PX), Image.LANCZOS).save(buf, "PNG", optimize=True)
    uri = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    (ROOT / "src/logo.ts").write_text(
        "// SPDX-License-Identifier: GPL-3.0-or-later\n"
        "// Generated by tools/make_logo_assets.py from docs/img/logo.png. Do not edit.\n"
        f'export const LOGO = "{uri}";\n')


if __name__ == "__main__":
    main()
